"""Project Oogie, HLE renderer stage 0: the D3D8 entry points the game calls.

Reads the XBE's section table (game/default.xbe) and the disassembly's
cross-references (build_out/disasm/xrefs.json), and lists every function in
the D3D library section that code outside it calls directly or stores as a
pointer: the API surface a high-level renderer has to provide. Writes
docs/D3D8_API_INVENTORY.md (addresses only; names are added as functions are
identified).

Usage: py -3 scripts/d3d_api_inventory.py
"""
import collections
import json
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def sections():
    xbe = open(os.path.join(ROOT, "game", "default.xbe"), "rb").read()
    base = struct.unpack_from("<I", xbe, 0x104)[0]
    count = struct.unpack_from("<I", xbe, 0x11C)[0]
    table = struct.unpack_from("<I", xbe, 0x120)[0]
    out = []
    for i in range(count):
        o = table - base + i * 56
        _flags, va, vsize, _raw, _rsize, name_va = struct.unpack_from("<IIIIII", xbe, o)
        name = xbe[name_va - base:name_va - base + 16].split(b"\0")[0].decode("latin1")
        out.append((name, va, va + vsize))
    return out


def main():
    secs = sections()

    def sec_of(va):
        for name, lo, hi in secs:
            if lo <= va < hi:
                return name
        return None

    d3d = [s for s in secs if s[0] == "D3D"]
    if not d3d:
        raise SystemExit("no D3D section: " + ", ".join(s[0] for s in secs))
    funcs = json.load(open(os.path.join(ROOT, "build_out", "disasm", "functions.json")))
    items = funcs if isinstance(funcs, list) else funcs.get("functions", funcs)
    starts = set()
    for f in (items.values() if isinstance(items, dict) else items):
        s = f.get("start")
        starts.add(int(s, 16) if isinstance(s, str) else s)
    callers = collections.defaultdict(set)
    kinds = collections.defaultdict(set)
    for x in json.load(open(os.path.join(ROOT, "build_out", "disasm", "xrefs.json"))):
        src, dst = int(x["from"], 16), int(x["to"], 16)
        if sec_of(dst) != "D3D" or sec_of(src) == "D3D" or dst not in starts:
            continue
        callers[dst].add(sec_of(src))
        kinds[dst].add(x.get("type", "?"))
    lines = ["# D3D8 entry points used from outside the D3D library", "",
             "Generated by scripts/d3d_api_inventory.py from build_out/disasm/xrefs.json and the XBE section",
             "table. Each row is a function in the D3D section that code outside it calls (or stores as",
             "a pointer): what a high-level renderer has to provide. Calls per frame come from",
             "OOGIE_D3D_CALLS=1 (recomp_manual.c); names are filled in as functions are identified.", "",
             "Sections: " + ", ".join("%s 0x%08X-0x%08X" % s for s in secs if s[0] in ("D3D", ".text", "D3DX", "XGRPH")), "",
             "| Address | Called from sections | Reference kinds | Name (identified) |", "|---|---|---|---|"]
    for va in sorted(callers):
        lines.append("| 0x%08X | %s | %s | |" % (va, ", ".join(sorted(callers[va])), ", ".join(sorted(kinds[va]))))
    lines.append("")
    lines.append("%d entry points." % len(callers))
    open(os.path.join(ROOT, "docs", "D3D8_API_INVENTORY.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("D3D section 0x%08X-0x%08X; %d entry points used from outside it" % (d3d[0][1], d3d[0][2], len(callers)))
    by = collections.Counter(s for v in callers.values() for s in v)
    print("callers by section:", dict(by))


if __name__ == "__main__":
    main()
